def _update_seeded_config(bind) -> None:
    """Brings a database seeded in slice 1 up to date. Does nothing on an empty database
    (the seed script fills that), so seeding and migrating never fight each other."""
    stages_present = bind.execute(sa.text("SELECT count(*) FROM stages")).scalar()
    if stages_present:
        for old, new in STAGE_RENAMES.items():
            bind.execute(
                sa.text(
                    "UPDATE stages SET name = CAST(:new AS VARCHAR) WHERE name = CAST(:old AS VARCHAR) "
                    "AND NOT EXISTS (SELECT 1 FROM stages WHERE name = CAST(:new AS VARCHAR))"
                ),
                {"old": old, "new": new},
            )
        for order, (name, outcome) in enumerate(STAGES, start=1):
            exists = bind.execute(sa.text("SELECT 1 FROM stages WHERE name = :n"), {"n": name}).scalar()
            if exists:
                bind.execute(
                    sa.text("UPDATE stages SET sort_order = :o, outcome = :oc WHERE name = :n"),
                    {"o": order, "oc": outcome, "n": name},
                )
            else:
                bind.execute(
                    sa.text("INSERT INTO stages (name, sort_order, outcome) VALUES (:n, :o, :oc)"),
                    {"n": name, "o": order, "oc": outcome},
                )

    types_present = bind.execute(sa.text("SELECT count(*) FROM activity_types")).scalar()
    if types_present:
        for name, channel, minutes in NEW_ACTIVITY_TYPES:
            bind.execute(
                sa.text(
                    "INSERT INTO activity_types (name, channel, default_duration_min) "
                    "SELECT CAST(:n AS VARCHAR), CAST(:c AS VARCHAR), CAST(:m AS INTEGER) "
                    "WHERE NOT EXISTS (SELECT 1 FROM activity_types WHERE name = CAST(:n AS VARCHAR))"
                ),
                {"n": name, "c": channel, "m": minutes},
            )
        for order, name in enumerate(ACTIVITY_TYPE_ORDER, start=1):
            bind.execute(
                sa.text("UPDATE activity_types SET sort_order = :o WHERE name = :n"), {"o": order, "n": name}
            )

    # Delivery clock: each product's delivery days after the purchase order.
    bind.execute(sa.text("UPDATE products SET delivery_days = 90 WHERE category = 'kit' AND delivery_days = 0"))
